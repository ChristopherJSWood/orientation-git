// Golden traces: records full seeded play-throughs from the reference engine.
// The Swift test suite replays every trace and must match step for step, which
// proves the two engines implement the same rules.
//
// Usage: node tools/golden.mjs          (rewrite the fixture)
//        node tools/golden.mjs --check  (fail if the fixture is stale)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { Game, METERS, formatClock, mulberry32, snapshot } from "./engine.mjs";
import { DEFAULT_CONTENT } from "./validate.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const FIXTURE = resolve(here, "../Core/Tests/BedtimeCoreTests/Fixtures/golden.json");

// Deterministic policy that needs no RNG, so both engines can reproduce it.
export const policyIndex = (seed, step, count) => (seed + step * 31) % count;

export function buildGolden(content) {
  const seeds = [0, 1, 2, 7, 42, 1234, 99999, 2147483647, 2147483648, 4294967295];
  const r = mulberry32(20261123);
  while (seeds.length < 40) seeds.push(Math.floor(r() * 4294967296));

  const rng = mulberry32(0);
  const rngSamples = Array.from({ length: 8 }, () => rng());
  const rngSeed = mulberry32(4294967295);
  const rngSamplesMax = Array.from({ length: 8 }, () => rngSeed());

  const traces = seeds.map((seed) => {
    const g = new Game(content, seed);
    const steps = [];
    while (!g.isOver) {
      const n = g.visibleChoices().length;
      const c = policyIndex(seed, g.state.step, n);
      const res = g.choose(c);
      steps.push({ e: res.eventId, n, c, o: res.outcomeIndex, clock: g.state.clock, m: METERS.map((k) => g.state.meters[k]) });
    }
    return { seed, modifierId: g.state.modifierId, steps, final: snapshot(g) };
  });

  const clocks = [0, 360, 365, 719, 720, 765, 1170, 1439, 1440];
  return {
    note: "GENERATED by tools/golden.mjs from tools/engine.mjs + content.json. Do not edit by hand.",
    meters: METERS,
    rng: { seed0: rngSamples, seedMax: rngSamplesMax },
    clockFormat: clocks.map((m) => [m, formatClock(m)]),
    traces,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const content = JSON.parse(readFileSync(DEFAULT_CONTENT, "utf8"));
  const next = JSON.stringify(buildGolden(content), null, 1) + "\n";
  if (process.argv.includes("--check")) {
    const cur = existsSync(FIXTURE) ? readFileSync(FIXTURE, "utf8") : "";
    if (cur !== next) {
      console.log("golden.json is stale: run `node tools/golden.mjs` and commit the result.");
      process.exit(1);
    }
    console.log("golden.json is up to date.");
  } else {
    writeFileSync(FIXTURE, next);
    const t = JSON.parse(next).traces;
    console.log(`wrote ${t.length} traces (${t.reduce((a, x) => a + x.steps.length, 0)} steps) to ${FIXTURE}`);
  }
}
