// Builds the single-file web playtest build from the same engine and content
// the iOS app uses, so a browser play session tests the real rules.
//
// Usage: node tools/build-prototype.mjs                 (writes prototype/index.html)
//        node tools/build-prototype.mjs --check         (fail if index.html is stale)
//        node tools/build-prototype.mjs --fragment out  (also write a skeleton-less copy for hosts that add their own <html>/<head>)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { DEFAULT_CONTENT } from "./validate.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const TEMPLATE = resolve(here, "../prototype/template.html");
const OUT = resolve(here, "../prototype/index.html");
const ENGINE = resolve(here, "engine.mjs");

export function buildFragment() {
  const template = readFileSync(TEMPLATE, "utf8");
  const engine = readFileSync(ENGINE, "utf8").replace(/^export /gm, "");
  const content = JSON.parse(readFileSync(DEFAULT_CONTENT, "utf8"));
  // Escape "</" so content text can never close the <script> element early.
  const contentJs = `const CONTENT = ${JSON.stringify(content).replace(/<\//g, "<\\/")};`;
  if (!template.includes("/*__ENGINE__*/") || !template.includes("/*__CONTENT__*/")) {
    throw new Error("template.html is missing a placeholder");
  }
  // Function replacers: content contains "$3.49", which a string replacement would misread.
  return template.replace("/*__ENGINE__*/", () => engine).replace("/*__CONTENT__*/", () => contentJs);
}

export function buildStandalone() {
  return [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
    "<!-- GENERATED by tools/build-prototype.mjs from prototype/template.html. Do not edit. -->",
    "</head>",
    "<body>",
    buildFragment(),
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const html = buildStandalone();
  if (args.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== html) {
      console.log("prototype/index.html is stale: run `node tools/build-prototype.mjs` and commit it.");
      process.exit(1);
    }
    console.log("prototype/index.html is up to date.");
  } else {
    writeFileSync(OUT, html);
    console.log(`wrote ${OUT} (${(html.length / 1024).toFixed(1)} KB)`);
    const i = args.indexOf("--fragment");
    if (i >= 0 && args[i + 1]) {
      writeFileSync(resolve(args[i + 1]), buildFragment());
      console.log(`wrote fragment ${resolve(args[i + 1])}`);
    }
  }
}
